import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { fixture, fakeNavidrome } from './helpers.js';
const login = f => f.request('/api/music/login', { method: 'POST', data: { username: 'demo', password: 'finta' } });
test('musica: stelle, scrobble idempotente, recenti, più ascoltati e isolamento utente', async t => {
  const nav = await fakeNavidrome(); t.after(() => nav.close());
  const f = await fixture({ navidromeUrl: nav.url }); t.after(() => f.close());
  assert.equal((await f.request('/api/music/activity')).status, 401); await login(f);
  assert.equal((await f.request('/api/music/star', { method: 'POST', data: { id: 's1', starred: true } })).status, 200);
  assert.equal((await (await f.request('/api/music/liked')).json()).songs[0].id, 's1');
  for (let n = 0; n < 2; n++) assert.equal((await f.request('/api/music/listen', { method: 'POST', data: { id: 's1', playId: 'prova-1', submission: true } })).status, 200);
  assert.equal(nav.calls.filter(c => c.method === 'scrobble').length, 1);
  const activity = await (await f.request('/api/music/activity')).json();
  assert.equal(activity.top[0].count, 1); assert.equal(activity.recent[0].id, 's1');
  await f.request('/api/music/login', { method: 'POST', data: { username: 'altro', password: 'finta' } });
  assert.equal((await (await f.request('/api/music/activity')).json()).recent.length, 0);
  assert.equal((await f.request('/api/music/star', { method: 'POST', data: { id: 's1', starred: 'sì' } })).status, 400);
});
test('catalogo arricchito per percorso, brani muti esclusi, radio senza ripetizioni e mix stabile', async t => {
  const songs = [1, 2, 3].map(i => ({ id: `s${i}`, title: `Finto ${i}`, path: `Libreria/${i}.mp3`, artist: `A${i}` }));
  const nav = await fakeNavidrome({ songs }); t.after(() => nav.close());
  const f = await fixture({ navidromeUrl: nav.url }); t.after(() => f.close()); await login(f);
  const folder = path.join(f.roots.Musica, 'Libreria'); await mkdir(folder);
  await writeFile(path.join(folder, 'catalogo_musica.json'), JSON.stringify({ versione: 1, mood: [{ nome: 'Relax' }], generi: [], brani: songs.map((s, i) => ({ file: `${i + 1}.mp3`, mood: ['Relax'], energia: 20 + i, bpm: 70, problema: i === 2 ? 'muto' : undefined })) }));
  const select = data => f.request('/api/music/select', { method: 'POST', data });
  const first = await (await select({ kind: 'mix', mood: 'Relax' })).json();
  assert.equal(first.songs.length, 2); assert.equal(first.songs[0].energia >= 20, true);
  assert.deepEqual((await (await select({ kind: 'mix', mood: 'Relax' })).json()).songs, first.songs);
  assert.equal((await (await select({ kind: 'radio', seed: 's1', exclude: ['s1', 's2'] })).json()).songs.length, 0);
  assert.equal((await (await f.request('/api/music/collection?type=mood&name=Relax')).json()).songs.length, 2);
  assert.equal((await select({ kind: 'inventato' })).status, 400);
});
test('playlist vuota, sostituzione ordinata con duplicati, aggiunta e ricerca playlist', async t => {
  const nav = await fakeNavidrome(); t.after(() => nav.close());
  const f = await fixture({ navidromeUrl: nav.url }); t.after(() => f.close()); await login(f);
  assert.equal((await f.request('/api/music/playlist', { method: 'PUT', data: { id: 'p1', name: 'Vuota', songs: [] } })).status, 200);
  assert.deepEqual(nav.calls.find(c => c.method === 'updatePlaylist').params.getAll('songIndexToRemove'), ['0']);
  await f.request('/api/music/playlist', { method: 'PUT', data: { id: 'p1', name: 'Due', songs: ['s1', 's1'] } });
  assert.deepEqual(nav.calls.find(c => c.method === 'createPlaylist').params.getAll('songId'), ['s1', 's1']);
  await f.request('/api/music/playlist/add', { method: 'POST', data: { id: 'p1', song: 's1' } });
  assert.equal(nav.calls.at(-1).method, 'updatePlaylist');
  assert.equal((await (await f.request('/api/music/playlist?id=p1')).json()).playlist.entry.length, 3);
  assert.ok((await (await f.request('/api/music/search?q=Due')).json()).playlists.playlist.length);
  await f.request('/api/music/cover?id=a1&size=80'); assert.equal(nav.calls.at(-1).params.get('size'), '80');
  const long = await f.request('/api/music/playlist', { method: 'POST', data: { name: 'Lunga finta', songs: Array(2000).fill('s1') } });
  assert.equal(long.status, 200); assert.equal(nav.calls.at(-1).verb, 'POST'); assert.equal((await long.json()).playlist.entry.length, 2000);
});
